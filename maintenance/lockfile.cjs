// Convert the audited npm dependency graph to Yarn v1 without losing integrity
// metadata or optional platform packages. npm's temporary lock is not committed.
const fs = require('node:fs');
const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const entries = new Map();
const conflicts = [];
function locate(from, name) {
  let parent = from;
  while (true) {
    const key = `${parent ? parent + '/' : ''}node_modules/${name}`;
    if (lock.packages[key]) return [key, lock.packages[key]];
    if (!parent) throw new Error(`Unresolved ${name} from ${from}`);
    const i = parent.lastIndexOf('/node_modules/');
    parent = i >= 0 ? parent.slice(0, i) : '';
  }
}
function visit(name, range, from) {
  const [path, item] = locate(from, name);
  const key = `${name}@${range}`;
  if (entries.has(key)) {
    if (entries.get(key).version !== item.version) conflicts.push(key);
    return;
  }
  if (!item.resolved || !item.integrity) throw Error(`Missing provenance: ${path}`);
  const entry = {version:item.version, resolved:item.resolved, integrity:item.integrity};
  entries.set(key, entry);
  for (const field of ['dependencies','optionalDependencies']) {
    if (!item[field] || !Object.keys(item[field]).length) continue;
    entry[field] = item[field];
    for (const [child, spec] of Object.entries(item[field])) visit(child, spec, path);
  }
}
for (const field of ['dependencies','devDependencies']) {
  for (const [name, range] of Object.entries(pkg[field] || {})) visit(name, range, '');
}
for (const [name, range] of Object.entries(pkg.resolutions || {})) {
  if (!name.includes('/')) visit(name, range, '');
}
if (conflicts.length) throw Error(`Ambiguous Yarn selectors: ${[...new Set(conflicts)].join(', ')}`);
let output = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n';
const groups = new Map();
for (const [key, value] of [...entries].sort(([a],[b])=>a.localeCompare(b))) {
  const identity = JSON.stringify(value);
  if (!groups.has(identity)) groups.set(identity, { keys: [], value });
  groups.get(identity).keys.push(key);
}
for (const {keys, value} of groups.values()) {
  output += `\n${keys.map(key=>JSON.stringify(key)).join(', ')}:\n`;
  for (const [field, val] of Object.entries(value)) {
    if (typeof val === 'string') output += `  ${field} ${JSON.stringify(val)}\n`;
    else {
      output += `  ${field}:\n`;
      for (const [name, range] of Object.entries(val).sort(([a],[b])=>a.localeCompare(b))) output += `    ${JSON.stringify(name)} ${JSON.stringify(range)}\n`;
    }
  }
}
fs.writeFileSync('yarn.lock', output);
console.log(`Validated ${entries.size} selectors; complete URLs, integrity hashes and optional dependencies`);
